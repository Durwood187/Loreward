// Build script for the SpoilerShield extension.
//
// What it does, in order:
//   1. Reads every JSON file in data/series/ and writes src/generated/series-index.ts,
//      which imports them all. This is how a new series becomes a data-only change:
//      drop a JSON file in data/series/, rebuild, done. No TypeScript edits.
//   2. Bundles the content script and the popup script with esbuild.
//   3. Copies static files (manifest, popup HTML/CSS, content CSS, icons) into dist/.
//
// Usage:  node scripts/build.mjs            one-off build
//         node scripts/build.mjs --watch    rebuild on change
//         node scripts/build.mjs --gen-only only step 1 (used by `npm run typecheck`)

import * as esbuild from 'esbuild';
import { readdirSync, mkdirSync, writeFileSync, copyFileSync, rmSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');
const args = new Set(process.argv.slice(2));

function generateSeriesIndex() {
  const dir = join(root, 'data', 'series');
  const files = readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
  const lines = [
    '// AUTO-GENERATED by scripts/build.mjs from data/series/*.json. Do not edit.',
    "import type { SeriesData } from '../core/types';",
  ];
  files.forEach((f, i) => lines.push(`import s${i} from '../../data/series/${f}';`));
  lines.push(`export const ALL_SERIES: SeriesData[] = [${files.map((_, i) => `s${i} as SeriesData`).join(', ')}];`);
  mkdirSync(join(root, 'src', 'generated'), { recursive: true });
  writeFileSync(join(root, 'src', 'generated', 'series-index.ts'), lines.join('\n') + '\n');
  // Fail fast on duplicate series ids: two files claiming the same id is always a mistake.
  const ids = files.map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')).id);
  const dupes = ids.filter((id, i) => ids.indexOf(id) !== i);
  if (dupes.length) throw new Error(`Duplicate series id(s) in data/series: ${dupes.join(', ')}`);
  console.log(`series: ${ids.join(', ')}`);
}

function copyStatic() {
  const copies = [
    ['src/manifest.json', 'manifest.json'],
    ['src/popup/popup.html', 'popup.html'],
    ['src/popup/popup.css', 'popup.css'],
    ['src/content/content.css', 'content.css'],
  ];
  mkdirSync(join(dist, 'icons'), { recursive: true });
  for (const [from, to] of copies) copyFileSync(join(root, from), join(dist, to));
  for (const icon of readdirSync(join(root, 'public', 'icons'))) {
    copyFileSync(join(root, 'public', 'icons', icon), join(dist, 'icons', icon));
  }
}

generateSeriesIndex();
if (args.has('--gen-only')) process.exit(0);

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
copyStatic();

const options = {
  entryPoints: {
    content: join(root, 'src/content/index.ts'),
    popup: join(root, 'src/popup/popup.ts'),
  },
  outdir: dist,
  bundle: true,
  format: 'iife', // content scripts can't be ES modules; IIFE works everywhere
  target: 'chrome120',
  sourcemap: args.has('--watch') ? 'inline' : false,
  logLevel: 'info',
};

if (args.has('--watch')) {
  const ctx = await esbuild.context(options);
  await ctx.watch();
  console.log('watching… (static files are copied once; re-run if you change HTML/CSS/manifest)');
} else {
  await esbuild.build(options);
}
